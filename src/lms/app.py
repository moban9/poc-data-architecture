@app.post("/generate")
def generate(
    count: int = Query(default=1, ge=1, le=100_000),
    mode: str = Query(default="clean"),
    db: Session = Depends(get_db),
):
    if mode not in constants.VALID_GENERATE_MODES:
        raise HTTPException(400, f"mode must be one of {constants.VALID_GENERATE_MODES}")

    if mode == "clean":
        dirty_flags = [False] * count
    elif mode == "dirty":
        dirty_flags = [True] * count
    else:  # mixed — ~10% dirty
        dirty_flags = [random.random() < constants.MIXED_DIRTY_RATE for _ in range(count)]

    ensure_borrowers(db)

    loans: list[dict] = []
    schedules: list[dict] = []
    events: list[dict] = []
    dirty_count = 0
    mode_counts = {m: 0 for m in constants.DIRTY_MODES}
    mode_i = 0
    for is_dirty in dirty_flags:
        dirty_mode = None
        if is_dirty:
            dirty_mode = constants.DIRTY_MODES[mode_i % len(constants.DIRTY_MODES)]
            mode_i += 1
            dirty_count += 1
            mode_counts[dirty_mode] += 1
        loan, schedule, evs = _make_loan_unit(_new_id("L"), dirty_mode)
        loans.append(loan)
        schedules.extend(schedule)
        events.extend(evs)

    db.bulk_insert_mappings(models.Loan, loans)
    db.bulk_insert_mappings(models.RepaymentSchedule, schedules)
    db.bulk_insert_mappings(models.LoanEvent, events)
    db.commit()

    LOANS_GENERATED.labels(mode=mode).inc(len(loans))
    LOAN_EVENTS_GENERATED.labels(mode=mode).inc(len(events))

    return {
        "mode": mode,
        "requested": count,
        "loans": len(loans),
        "repayment_schedule": len(schedules),
        "loan_events": len(events),
        "borrowers_ensured": len(constants.SEED_BORROWERS),
        "dirty": dirty_count,
        "dirty_modes": mode_counts,
    }


@app.post("/loans/{loan_id}/disburse", status_code=201)
def disburse(
    loan_id: str,
    body: Optional[DisburseRequest] = None,
    db: Session = Depends(get_db),
):
    loan = db.get(models.Loan, loan_id)
    if loan is None:
        raise HTTPException(404, f"loan '{loan_id}' not found")

    amount = body.amount if body and body.amount is not None else float(loan.amount)
    occurred_at = _coerce_utc(body.occurred_at) if body and body.occurred_at else _now()

    event = models.LoanEvent(
        id=_new_id("E"), loan_id=loan_id, event_type="disbursement",
        amount=amount, occurred_at=occurred_at,
    )
    db.add(event)
    db.commit()
    db.refresh(event)
    return {"loan_id": loan_id, "event": _event_to_dict(event)}


@app.post("/payments", status_code=201)
def record_payment(body: PaymentRequest, db: Session = Depends(get_db)):
    loan = db.get(models.Loan, body.loan_id)
    if loan is None:
        raise HTTPException(404, f"loan '{body.loan_id}' not found")

    occurred_at = _coerce_utc(body.occurred_at) if body.occurred_at else _now()
    event = models.LoanEvent(
        id=_new_id("E"), loan_id=body.loan_id, event_type="payment",
        amount=body.amount, occurred_at=occurred_at,
    )
    db.add(event)
    db.commit()
    db.refresh(event)
    return {"loan_id": body.loan_id, "event": _event_to_dict(event)}


@app.post("/scenarios/loan-book", status_code=201)
def create_loan_book(body: LoanBookRequest, db: Session = Depends(get_db)):
    """Create loans with a REAL repayment schedule so every dbt Gold
    delinquency bucket (current / 30-59 / 60-89 / 90+) is populated from
    ``repayment_schedule.due_date``.

    Each loan amortizes monthly from ``disbursement_date``; instalments are
    ``paid`` / ``overdue`` / ``scheduled`` so the oldest overdue ``due_date``
    encodes the target days-past-due. Total paid < principal (outstanding > 0).
    Generates fresh ids and never deletes rows, so repeated calls only add
    data. Writes loans + schedules + events in a single transaction.
    """
    now = _now()
    ensure_borrowers(db)

    all_loans: list[dict] = []
    all_schedules: list[dict] = []
    all_events: list[dict] = []
    per_bucket: dict[str, dict] = {}

    for bucket, spec in NPL_BUCKETS.items():
        bucket_payments = 0
        bucket_overdue = 0
        for _ in range(body.n_per_bucket):
            loan, schedule, events = _loan_book_unit(now, bucket)
            all_loans.append(loan)
            all_schedules.extend(schedule)
            all_events.extend(events)
            bucket_payments += sum(1 for e in events if e["event_type"] == "payment")
            bucket_overdue += sum(1 for s in schedule if s["status"] == constants.REPAYMENT_STATUS_OVERDUE)
        per_bucket[bucket] = {
            "label": spec["label"],
            "gold_bucket": spec["gold_bucket"],
            "days_past_due": spec["days_past_due"],
            "loans": body.n_per_bucket,
            "payments": bucket_payments,
            "overdue_installments": bucket_overdue,
        }

    db.bulk_insert_mappings(models.Loan, all_loans)
    db.bulk_insert_mappings(models.RepaymentSchedule, all_schedules)
    db.bulk_insert_mappings(models.LoanEvent, all_events)
    db.commit()

    LOANS_GENERATED.labels(mode="loan-book").inc(len(all_loans))
    LOAN_EVENTS_GENERATED.labels(mode="loan-book").inc(len(all_events))

    total_payments = sum(b["payments"] for b in per_bucket.values())
    return {
        "created_loans": len(all_loans),
        "payments": total_payments,
        "repayment_schedule": len(all_schedules),
        "loan_events": len(all_events),
        "n_per_bucket": body.n_per_bucket,
        "per_bucket": per_bucket,
    }


