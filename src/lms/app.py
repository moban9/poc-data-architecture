@app.post("/generate")
def generate(
    count: int = Query(default=1, ge=1, le=100_000),
    mode: str = Query(default="clean"),
    db: Session = Depends(get_db),
):
    if mode not in constants.VALID_GENERATE_MODES:
        raise HTTPException(400, f"mode must be one of {constants.VALID_GENERATE_MODES}")

    if mode == "clean":
        dirty_flags = [False] * count
    elif mode == "dirty":
        dirty_flags = [True] * count
    else:  # mixed — ~10% dirty
        dirty_flags = [random.random() < constants.MIXED_DIRTY_RATE for _ in range(count)]

    ensure_borrowers(db)

    _log = logging.getLogger("lms.generate")
    _t_start = time.perf_counter()
    _flush_s = 0.0
    _flushes = 0

    loans: list[dict] = []
    schedules: list = []  # list of tuples (RepaymentSchedule column order)
    events: list[dict] = []
    dirty_count = 0
    mode_counts = {m: 0 for m in constants.DIRTY_MODES}
    mode_i = 0
    chunk = 1000
    total_schedules = 0
    total_events = 0

    def _flush() -> float:
        # PostgreSQL COPY instead of bulk_insert_mappings — the schedule is the
        # hot table (~195k rows) and this skips SQLAlchemy's per-row dict→row
        # conversion + driver round-trips. Chunking (1000 loans/batch) is
        # preserved to stay well under the 512MB container cap.
        _t = time.perf_counter()
        _bulk_insert(db, models.Loan, loans)
        _bulk_insert(db, models.RepaymentSchedule, schedules)
        _bulk_insert(db, models.LoanEvent, events)
        db.commit()
        loans.clear()
        schedules.clear()
        events.clear()
        return time.perf_counter() - _t

    for is_dirty in dirty_flags:
        dirty_mode = None
        if is_dirty:
            dirty_mode = constants.DIRTY_MODES[mode_i % len(constants.DIRTY_MODES)]
            mode_i += 1
            dirty_count += 1
            mode_counts[dirty_mode] += 1
        loan, schedule, evs = _make_loan_unit_rows(_new_id("L"), dirty_mode)
        loans.append(loan)
        schedules.extend(schedule)
        events.extend(evs)
        total_schedules += len(schedule)
        total_events += len(evs)
        if len(loans) >= chunk:
            _flush_s += _flush()
            _flushes += 1

    if loans:
        _flush_s += _flush()
        _flushes += 1

    if os.getenv("LMS_TIMING"):
        _total = time.perf_counter() - _t_start
        _log.info(
            "timing count=%d total=%.2fs flush=%.2fs build=%.2fs flushes=%d rows_sched=%d",
            count,
            _total,
            _flush_s,
            _total - _flush_s,
            _flushes,
            total_schedules,
        )

    LOANS_GENERATED.labels(mode=mode).inc(count)
    LOAN_EVENTS_GENERATED.labels(mode=mode).inc(total_events)

    return {
        "mode": mode,
        "requested": count,
        "loans": count,
        "repayment_schedule": total_schedules,
        "loan_events": total_events,
        "borrowers_ensured": len(constants.SEED_BORROWERS),
        "dirty": dirty_count,
        "dirty_modes": mode_counts,
    }


@app.post("/loans/{loan_id}/disburse", status_code=201)
def disburse(
    loan_id: str,
    body: Optional[DisburseRequest] = None,
    db: Session = Depends(get_db),
):
    loan = db.get(models.Loan, loan_id)
    if loan is None:
        raise HTTPException(404, f"loan '{loan_id}' not found")

    amount = body.amount if body and body.amount is not None else float(loan.amount)
    occurred_at = _coerce_utc(body.occurred_at) if body and body.occurred_at else _now()

    event = models.LoanEvent(
        id=_new_id("E"), loan_id=loan_id, event_type="disbursement",
        amount=amount, occurred_at=occurred_at,
    )
    db.add(event)
    db.commit()
    db.refresh(event)
    return {"loan_id": loan_id, "event": _event_to_dict(event)}


